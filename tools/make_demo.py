"""A shareable demo page of one battle, e.g. for GitHub Pages:

    python tools/make_demo.py REPLAY [-o docs/index.html]

By default a split page, like the library server's: index.html holds the viewer and the battle, and the files it
needs sit beside it (assets/: minimap, ship and class icons, and - fetched only when 3D opens - ship models and
terrain; three.js as its own file), so the first load is small and the browser caches the rest. Needs a web server
(GitHub Pages, or python -m http.server for a local look): browsers won't fetch files next to a file:// page.
--single-file embeds everything in one page instead (~10 MB, opens from disk); --no-wg-assets leaves the Wargaming
files out altogether (grid-only 2D map, placeholder hulls in 3D).

Other players are anonymised: names become 'Ally 3' / 'Enemy 5', clan tags and the chat (it carries account ids) are
dropped. Your own name stays (--hide-me replaces it with 'You'). The page is checked afterwards: it must not contain
any original name, clan tag or account id.
"""
import argparse
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path[:0] = [ROOT]

from wowsreplay.__main__ import DATA, THREE_JS, build_data, render_page  # noqa: E402
from wowsreplay.privacy import anonymise, leaks  # noqa: E402

ASSETS = 'assets/'   # relative: works at any path (GitHub Pages serves the repo under /<repo>/)


def asset_refs(v):
    """Every 'assets/...' URL in the page data."""
    if isinstance(v, str):
        if v.startswith(ASSETS):
            yield v
    elif isinstance(v, dict):
        for x in v.values():
            yield from asset_refs(x)
    elif isinstance(v, list):
        for x in v:
            yield from asset_refs(x)


def write_assets(data, out_dir):
    """Copy the files the page references into out_dir/assets/ (rebuilt from scratch), three.js next to the page.
    Returns {'first load': bytes, '3D only': bytes} of the copied files."""
    dest = os.path.join(out_dir, 'assets')
    if os.path.isdir(dest):
        shutil.rmtree(dest)   # generated by this tool only: drop files an earlier battle needed
    sizes = {'first load': 0, '3D only': 0}
    three_d = set(data.get('modelUrls', {}).values()) | {((data.get('map') or {}).get('terrain') or {}).get('url')}
    for url in sorted(set(asset_refs(data))):
        rel = url[len(ASSETS):]
        src = os.path.normpath(os.path.join(DATA, rel))
        if not src.startswith(os.path.normpath(DATA) + os.sep):
            sys.exit(f'refusing to copy {url}: outside the game data folder')
        dst = os.path.join(dest, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        sizes['3D only' if url in three_d else 'first load'] += os.path.getsize(dst)
    for src in (THREE_JS, os.path.join(os.path.dirname(THREE_JS), 'three.LICENSE')):
        shutil.copyfile(src, os.path.join(out_dir, os.path.basename(src)))
    sizes['first load'] += os.path.getsize(THREE_JS)
    return sizes


def main(argv=None):
    ap = argparse.ArgumentParser(prog='python tools/make_demo.py', description=__doc__.split('\n\n')[0])
    ap.add_argument('replay', help='.wowsreplay file')
    ap.add_argument('-o', '--out', default=os.path.join(ROOT, 'docs', 'index.html'), help='default: docs/index.html')
    ap.add_argument('--hide-me', action='store_true', help="replace your own name with 'You' too")
    ap.add_argument('--single-file', action='store_true', help='embed everything in the one page (~10 MB)')
    ap.add_argument('--no-wg-assets', action='store_true',
                    help='leave out the Wargaming files (minimap, terrain, ship models, icons)')
    a = ap.parse_args(argv)

    split = not (a.single_file or a.no_wg_assets)
    if a.no_wg_assets:
        data = build_data(a.replay, embed=False)
        assert not (data['map'] or data['models'] or data['icons'] or data['classIcons'] or data['planeIcons'])
    else:
        data = build_data(a.replay, asset_base=ASSETS if split else None)
    secrets = anonymise(data, a.hide_me)
    page = render_page(data, three_url=os.path.basename(THREE_JS) if split else None)
    found = leaks(secrets, page)
    if found:
        sys.exit(f'refusing to write: the page still contains {len(found)} hidden name(s) / id(s)')
    out_dir = os.path.dirname(os.path.abspath(a.out))
    os.makedirs(out_dir, exist_ok=True)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write(page)
    m = data['meta']
    models = len(data.get('modelUrls') or data['models'])
    print(f'{a.out}: {len(page) / 1048576:.1f} MB | {m["map"]} | {m["gameType"]} | {len(data["ships"])} ships, '
          f'{len(secrets)} names / ids removed | map: {"yes" if data["map"] else "no"}, ship models: '
          f'{models} of {len({s["ship"] for s in data["ships"]})} types')
    if split:
        sizes = write_assets(data, out_dir)
        print(f'  + assets/ and three.js: {sizes["first load"] / 1048576:.1f} MB on first load (three.js, minimap, icons), '
              f'{sizes["3D only"] / 1048576:.1f} MB more when 3D opens (models, terrain)')


if __name__ == '__main__':
    main()
