"""Write tools/unpack_models.bat: a wowsunpack script that pulls the 3D models for some ships.

    python tools/make_unpack_models.py wows_gamedata.zip PGSB310_Preussen PRSC208_Tallin PBSB510_Thunderer [--no-textures]

Every *.model path in each ship's GameParams entry (hull, turrets, directors, rangefinders, radars...)
gives a folder to extract whole (.geometry etc.). Textures are taken as the small .dds only, matched by
the model id; the .dd0-.dd2 full-resolution mips are skipped. content/assets.bin (the model/visual
database) is always included.
"""
import os
import sys
import zipfile
import zlib

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from wowsreplay.safe_pickle import Opaque, loads  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))

HEAD = r'''@echo off
rem Generated by tools/make_unpack_models.py for: {ships}
rem Usage: put this file and wowsunpack.exe (from ModSDK) in one folder, then
rem        unpack_models.bat "C:\Games\World_of_Warships"
rem Reads from the game only. Writes to .\wows_models and zips it to .\wows_models.zip.
setlocal
if "%~1"=="" (
    echo usage: %~nx0 "path\to\World_of_Warships"
    exit /b 1
)
set "GAME=%~1"
set "HERE=%~dp0"
set "UNPACK=%HERE%wowsunpack.exe"
set "OUT=%HERE%wows_models"
if not exist "%UNPACK%" (
    echo wowsunpack.exe not found next to this script
    exit /b 1
)
set "BUILD="
for /f "delims=" %%d in ('dir /b /ad /o-n "%GAME%\bin"') do (
    if not defined BUILD if exist "%GAME%\bin\%%d\idx" set "BUILD=%%d"
)
if not defined BUILD (
    echo no bin\^<build^>\idx folder found
    exit /b 1
)
set "IDX=%GAME%\bin\%BUILD%\idx"
set "PKG=..\..\..\res_packages"
set "LOG=%OUT%\extract_log.txt"
if not exist "%OUT%" mkdir "%OUT%"
echo build %BUILD% > "%LOG%"

echo assets.bin...
"%UNPACK%" -x "%IDX%" -p "%PKG%" -o "%OUT%" -I "content/assets.bin" >> "%LOG%" 2>&1
'''

TAIL = r'''
echo zipping...
if exist "%HERE%wows_models.zip" del "%HERE%wows_models.zip"
powershell -NoProfile -Command "Compress-Archive -Path '%OUT%\*' -DestinationPath '%HERE%wows_models.zip'"
echo done: %HERE%wows_models.zip
endlocal
'''


def model_dirs(gp, ship):
    out = set()

    def walk(o, depth):
        o = o.state if isinstance(o, Opaque) else o
        if depth > 5 or not isinstance(o, dict):
            return
        for v in o.values():
            if isinstance(v, str) and v.endswith('.model'):
                out.add(os.path.dirname(v).replace('\\', '/'))
            else:
                walk(v, depth + 1)

    walk(gp[ship], 0)
    return out


def main(argv):
    textures = '--no-textures' not in argv
    argv = [a for a in argv if a != '--no-textures']
    if len(argv) < 2:
        sys.exit(__doc__)
    z = zipfile.ZipFile(argv[0])
    name = next(n for n in z.namelist() if n.replace('\\', '/').endswith('content/GameParams.data'))
    gp = loads(zlib.decompress(z.read(name)[::-1]), encoding='latin1')['']
    dirs = set()
    for ship in argv[1:]:
        if ship not in gp:
            sys.exit(f'{ship} not in GameParams (use the full key, e.g. PGSB310_Preussen)')
        dirs |= model_dirs(gp, ship)
    dirs = sorted(dirs)
    for d in dirs:
        if any(c in d for c in '"%&|<>^'):
            sys.exit(f'unexpected characters in model path: {d}')

    lines = [HEAD.format(ships=' '.join(argv[1:]))]
    for i, d in enumerate(dirs, 1):
        mid = d.rsplit('/', 1)[1]
        lines.append(f'echo [{i}/{len(dirs)}] {mid}\n'
                     f'"%UNPACK%" -x "%IDX%" -p "%PKG%" -o "%OUT%" -I "{d}/*" >> "%LOG%" 2>&1\n')
        if textures:
            lines.append(f'"%UNPACK%" -x "%IDX%" -p "%PKG%" -o "%OUT%" -I "*{mid}*.dds" >> "%LOG%" 2>&1\n')
    lines.append(TAIL)
    path = os.path.join(HERE, 'unpack_models.bat')
    with open(path, 'w', encoding='ascii', newline='\r\n') as f:
        f.write(''.join(lines))
    print(f'{path}: {len(dirs)} model folders for {len(argv) - 1} ships')


if __name__ == '__main__':
    main(sys.argv[1:])
